/**
 * The Fluent Emoji drawings the funnel shows, taken from the app's own set
 * (src/shared/ui/fluent-icon/icons.ts) so the two never drift. Only the ones
 * named here are written, which keeps the other ~60 KB out of the bundle.
 * Run: bun scripts/icons.ts
 */
import { writeFileSync } from 'node:fs';

import { FLUENT_ICONS } from '../../src/shared/ui/fluent-icon/icons';

const NAMES = [
  'foot', 'leg', 'balance', 'sandal', 'runningShoe', 'briefcase',
  'sunrise', 'couch', 'sun', 'moon', 'leafInWind',
  'healthWorker', 'softball', 'seedling',
  'bed', 'bandage', 'feather', 'crutch', 'check',
  'stopwatch', 'calendar', 'sparkles', 'heart', 'bullseye', 'strength', 'bulb',
] as const;

const all: Readonly<Record<string, string>> = FLUENT_ICONS;
const lines = NAMES.map((name) => {
  const svg = all[name];
  if (svg == null) throw new Error(`icons: no "${name}" in the app's set`);
  return `  ${name}: ${JSON.stringify(svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, ''))},`;
});
writeFileSync(
  new URL('../src/icons.gen.ts', import.meta.url),
  `// Generated by scripts/icons.ts from the app's Fluent Emoji set. Do not edit.\nexport const ICONS = {\n${lines.join('\n')}\n} as const;\n\nexport type IconName = keyof typeof ICONS;\n`,
);
console.log(`icons: ${NAMES.length} drawings`);
